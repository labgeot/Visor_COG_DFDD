/** Simple Spanish inflection reducer (plurals & feminine/masculine endings). */
function spanishStemCandidates(token: string): string[] {
  const candidates = [token]
  if (token.endsWith("ces") && token.length > 4) {
    candidates.push(token.slice(0, -3) + "z")
  }
  if (token.endsWith("es") && token.length > 4) {
    candidates.push(token.slice(0, -2))
  }
  if (token.endsWith("s") && token.length > 3) {
    candidates.push(token.slice(0, -1))
  }
  if (token.endsWith("a") && token.length > 3) {
    candidates.push(token.slice(0, -1) + "o")
  }
  return candidates
}

function lookupWord(token: string): string[] {
  for (const cand of spanishStemCandidates(token)) {
    const hits = ES_EN_WORDS[cand]
    if (hits) return hits
  }
  return []
}

export interface ExpandedQuery {
  /** Normalized original query */
  rawNorm: string
  /** True when at least one Spanish -> English translation was applied */
  usedTranslation: boolean
  /**
   * Token groups that must match (AND across groups, OR within each group's synonyms).
   * For direct English/code queries, group[0] = [rawNorm].
   */
  groups: string[][]
  /** Flat list of translated English terms (for UI notice & highlighting) */
  translatedTerms: string[]
}

const normSimple = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()

/**
 * Expands a search query supporting both direct English/code matching and
 * Spanish -> English translation via the DFDD glossary.
 */
export function expandBilingualQuery(query: string): ExpandedQuery {
  const rawNorm = normSimple(query)
  if (!rawNorm) {
    return { rawNorm: "", usedTranslation: false, groups: [], translatedTerms: [] }
  }

  // 1. Exact phrase translation (e.g., "pista de aterrizaje" -> ["runway"])
  const phraseHits = ES_EN_PHRASES[rawNorm]
  if (phraseHits) {
    const terms = Array.from(new Set(phraseHits.map(normSimple)))
    return {
      rawNorm,
      usedTranslation: true,
      groups: [terms],
      translatedTerms: terms,
    }
  }

  // 2. Token-by-token inspection (checking 2-3 word phrases first, then individual tokens)
  const rawTokens = rawNorm.split(/\s+/).filter(Boolean)
  const meaningfulTokens = rawTokens.filter((t) => !STOPWORDS.has(t) || rawTokens.length === 1)

  const groups: string[][] = []
  const translatedSet = new Set<string>()
  let usedTranslation = false

  let i = 0
  while (i < meaningfulTokens.length) {
    // Try 2-word phrase within meaningful tokens
    if (i + 1 < meaningfulTokens.length) {
      const twoWord = `${meaningfulTokens[i]} ${meaningfulTokens[i + 1]}`
      const twoHit = ES_EN_PHRASES[twoWord]
      if (twoHit) {
        usedTranslation = true
        const mapped = twoHit.map(normSimple)
        mapped.forEach((m) => translatedSet.add(m))
        groups.push(Array.from(new Set([twoWord, ...mapped])))
        i += 2
        continue
      }
    }

    const tok = meaningfulTokens[i]
    const enHits = lookupWord(tok)
    if (enHits.length > 0) {
      usedTranslation = true
      const mapped = enHits.map(normSimple)
      mapped.forEach((m) => translatedSet.add(m))
      // Keep original token first (in case it's also a valid English/code substring) + English equivalents
      groups.push(Array.from(new Set([tok, ...mapped])))
    } else {
      groups.push([tok])
    }
    i += 1
  }

  return {
    rawNorm,
    usedTranslation,
    groups,
    translatedTerms: Array.from(translatedSet),
  }
}
